import json
from typing import Dict, List, Tuple, Optional
from dataclasses import dataclass

# AET Primitives mapping
AET_PRIMITIVES = {
    # State declarations
    "State": "state_declaration",
    "WaveState": "wave_state_declaration", 
    "Probability": "probability_declaration",
    "Embedding": "embedding_declaration",
    "ManifoldSpace": "manifold_declaration",
    
    # Operations
    "@": "linear_transform",
    ">>": "compose",
    "⊗": "superposition",
    "⊕": "entropy_gate",
    "Attention": "attention_mechanism",
    "CrossAttention": "cross_attention",
    "EntropyGate": "entropy_gate_op",
    "Collapse": "collapse_operation",
    "Superposition": "superposition_declaration",
    "WaveTransform": "wave_transform",
}

@dataclass
class AETNode:
    """Represents an AET syntax node"""
    type: str
    value: str
    children: List['AETNode'] = None
    metadata: Dict = None

class AETParser:
    """Parser for AET language"""
    
    def __init__(self):
        self.tokens = []
        self.pos = 0
        
    def parse(self, source: str) -> List[AETNode]:
        """Parse AET source into AST"""
        lines = source.split("\n")
        nodes = []
        
        for line in lines:
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            
            node = self._parse_line(line)
            if node:
                nodes.append(node)
        
        return nodes
    
    def _parse_line(self, line: str) -> Optional[AETNode]:
        """Parse a single line of AET"""
        
        # State declaration: state_name = State(...)
        state_match = re.match(r'(\w+)\s*=\s*(\w+)\s*\((.*)\)', line)
        if state_match:
            name, type_name, args = state_match.groups()
            return AETNode(
                type="declaration",
                value=name,
                children=[AETNode(type=type_name, value=args)],
                metadata={"category": "state_declaration"}
            )
        
        # Operation: result = input @ transform
        op_match = re.match(r'(\w+)\s*=\s*(\w+)\s*(@|>>|⊗|⊕)\s*(\w+)', line)
        if op_match:
            result, left, op, right = op_match.groups()
            return AETNode(
                type="operation",
                value=result,
                children=[
                    AETNode(type="operand", value=left),
                    AETNode(type="operator", value=op),
                    AETNode(type="operand", value=right)
                ],
                metadata={"category": "binary_operation"}
            )
        
        # Function call: Attention(query=..., memory=...)
        func_match = re.match(r'(\w+)\s*=\s*(\w+)\s*\((.*)\)', line)
        if func_match:
            result, func_name, args = func_match.groups()
            return AETNode(
                type="function_call",
                value=result,
                children=[AETNode(type="argument", value=args)],
                metadata={"category": "function", "name": func_name}
            )
        
        # Composition: a >> b >> c
        compose_match = re.match(r'(\w+)\s*=\s*(.+\s*>>\s*.+)', line)
        if compose_match:
            result, compose_expr = compose_match.groups()
            parts = [p.strip() for p in compose_expr.split(">>")]
            return AETNode(
                type="composition",
                value=result,
                children=[AETNode(type="path", value=">>".join(parts))],
                metadata={"category": "morphism_composition"}
            )
        
        return None

class AEONTranspiler:
    """Transpiles AET to target languages"""
    
    def __init__(self, target: str = "zig"):
        self.target = target
        self.parser = AETParser()
        
    def transpile(self, aet_source: str, target: str = None) -> str:
        """Transpile AET source to target language"""
        target = target or self.target
        
        nodes = self.parser.parse(aet_source)
        
        if target == "python":
            return self._to_python(nodes)
        elif target == "rust":
            return self._to_rust(nodes)
        elif target == "zig":
            return self._to_zig(nodes)
        elif target == "cuda":
            return self._to_cuda(nodes)
        else:
            raise ValueError(f"Unsupported target: {target}")
    
    def _to_python(self, nodes: List[AETNode]) -> str:
        """Transpile AET to Python"""
        output = ["# AET → Python transpiled code", "# Generated by AEON", ""]
        output.append("import numpy as np")
        output.append("from typing import List, Optional")
        output.append("import math")
        output.append("")
        
        for node in nodes:
            if node.type == "declaration":
                output.append(self._py_declaration(node))
            elif node.type == "operation":
                output.append(self._py_operation(node))
            elif node.type == "function_call":
                output.append(self._py_function(node))
            elif node.type == "composition":
                output.append(self._py_composition(node))
        
        return "\n".join(output)
    
    def _py_declaration(self, node: AETNode) -> str:
        """Python state declaration"""
        type_name = node.children[0].type
        name = node.value
        args = node.children[0].value
        
        if type_name == "State":
            # Parse dimensions
            dims = re.search(r'dimensions=(\d+)', args)
            init = re.search(r'initialization=(\w+)', args)
            dim = dims.group(1) if dims else "4096"
            init_val = init.group(1) if init else "zeros"
            
            init_code = f"np.{init_val}(({dim},))"
            return f"{name} = {init_code}"
        
        elif type_name == "WaveState":
            return f"{name} = np.zeros((), dtype=np.complex128)"
        
        elif type_name == "Probability":
            return f"{name} = np.array([1.0])  # Probability distribution"
        
        return f"# {name} = {type_name}({args})"
    
    def _py_operation(self, node: AETNode) -> str:
        """Python operation"""
        result = node.value
        op = node.children[1].value
        left = node.children[0].value
        right = node.children[2].value
        
        if op == "@":
            return f"{result} = np.matmul({left}, {right})"
        elif op == ">>":
            return f"{result} = {right}({left})"
        elif op == "⊗":
            return f"{result} = ({left}, {right})  # Superposition"
        
        return f"# {result} = {left} {op} {right}"
    
    def _py_function(self, node: AETNode) -> str:
        """Python function call"""
        func_name = node.metadata.get("name", "Unknown")
        result = node.value
        args = node.children[0].value
        
        if func_name == "Attention":
            # Parse attention arguments
            q_match = re.search(r'query=(\w+)', args)
            m_match = re.search(r'memory=(\w+)', args)
            k_match = re.search(r'top_k=(\d+)', args)
            
            query = q_match.group(1) if q_match else "query"
            memory = m_match.group(1) if m_match else "memory"
            top_k = k_match.group(1) if k_match else "10"
            
            return f"""
def attention_{result}(query, memory, top_k={top_k}):
    \"\"\"Attention mechanism\"\"\"
    scores = np.dot(query, memory.T) / np.sqrt(query.shape[-1])
    weights = np softmax(scores, axis=-1)
    return np.dot(weights, memory)
    
{result} = attention_{result}({query}, {memory}, {top_k})"""
        
        elif func_name == "WaveTransform":
            return f"{result} = wave_transform({args})"
        
        return f"{result} = {func_name}({args})"
    
    def _py_composition(self, node: AETNode) -> str:
        """Python composition"""
        path = node.children[0].value
        result = node.value
        parts = path.split(">>")
        
        func_calls = []
        for i, part in enumerate(parts):
            part = part.strip()
            if i == 0:
                func_calls.append(part)
            else:
                func_calls.append(f"{part}(last)")
        
        pipeline = " → ".join(parts)
        return f"{result}_pipeline = lambda x: " + "\n    ".join([f"{p}(x)" if i == 0 else f"{p}(_)" for i, p in enumerate(parts)])

    def _to_zig(self, nodes: List[AETNode]) -> str:
        """Transpile AET to Zig"""
        output = ["// AET → Zig transpiled code", "// Generated by AEON", ""]
        output.append("const std = @import(\"std\");")
        output.append("const math = std.math;")
        output.append("")
        
        for node in nodes:
            if node.type == "declaration":
                output.append(self._zig_declaration(node))
            elif node.type == "operation":
                output.append(self._zig_operation(node))
            elif node.type == "function_call":
                output.append(self._zig_function(node))
        
        return "\n".join(output)
    
    def _zig_declaration(self, node: AETNode) -> str:
        """Zig state declaration"""
        type_name = node.children[0].type
        name = node.value
        args = node.children[0].value
        
        if type_name == "State":
            dims = re.search(r'dimensions=(\d+)', args)
            dim = dims.group(1) if dims else "4096"
            return f"var {name}: [{dim}]f64 = undefined;"
        
        elif type_name == "WaveState":
            return f"var {name}: [1024]@Vector(2, f64) = undefined; // Wave state"
        
        elif type_name == "Probability":
            return f"var {name}: [100]f64 = undefined; // Probability distribution"
        
        return f"// {name} = {type_name}({args})"
    
    def _zig_operation(self, node: AETNode) -> str:
        """Zig operation"""
        result = node.value
        op = node.children[1].value
        left = node.children[0].value
        right = node.children[2].value
        
        if op == "@":
            return f"var {result}: [4096]f64 = undefined; // Matrix multiply {left} @ {right}"
        elif op == ">>":
            return f"var {result} = {right}({left});"
        
        return f"// {result} = {left} {op} {right}"
    
    def _zig_function(self, node: AETNode) -> str:
        """Zig function call"""
        func_name = node.metadata.get("name", "Unknown")
        result = node.value
        args = node.children[0].value
        
        if func_name == "Attention":
            return f"fn attention{result}(query: []const f64, memory: []const f64) []f64 {{}} // {args}"
        
        return f"// {result} = {func_name}({args})"
    
    def _to_rust(self, nodes: List[AETNode]) -> str:
        """Transpile AET to Rust"""
        output = ["// AET → Rust transpiled code", "// Generated by AEON", ""]
        output.append("use std::f64::consts::PI;")
        output.append("")
        
        for node in nodes:
            if node.type == "declaration":
                output.append(self._rust_declaration(node))
            elif node.type == "operation":
                output.append(self._rust_operation(node))
            elif node.type == "function_call":
                output.append(self._rust_function(node))
        
        return "\n".join(output)
    
    def _rust_declaration(self, node: AETNode) -> str:
        """Rust state declaration"""
        type_name = node.children[0].type
        name = node.value
        args = node.children[0].value
        
        if type_name == "State":
            dims = re.search(r'dimensions=(\d+)', args)
            dim = dims.group(1) if dims else "4096"
            return f"let mut {name}: Vec<f64> = vec![0.0; {dim}];"
        
        elif type_name == "WaveState":
            return f"let mut {name}: Vec<(f64, f64)> = Vec::new(); // Complex wave"
        
        return f"// {name} = {type_name}({args})"
    
    def _rust_operation(self, node: AETNode) -> str:
        """Rust operation"""
        result = node.value
        op = node.children[1].value
        left = node.children[0].value
        right = node.children[2].value
        
        if op == "@":
            return f"let mut {result} = matrix_mul(&{left}, &{right}); // Linear transform"
        elif op == ">>":
            return f"let mut {result} = {right}({left});"
        
        return f"// {result} = {left} {op} {right}"
    
    def _rust_function(self, node: AETNode) -> str:
        """Rust function call"""
        func_name = node.metadata.get("name", "Unknown")
        result = node.value
        args = node.children[0].value
        
        if func_name == "Attention":
            return f"fn attention_{result}(query: &[f64], memory: &[f64]) -> Vec<f64> {{}} // {args}"
        
        return f"// {result} = {func_name}({args})"
    
    def _to_cuda(self, nodes: List[AETNode]) -> str:
        """Transpile AET to CUDA"""
        output = ["// AET → CUDA transpiled code", "// Generated by AEON", ""]
        output.append("#include <cuda_runtime.h>")
        output.append("#include <cublas_v2.h>")
        output.append("")
        
        for node in nodes:
            if node.type == "declaration":
                output.append(self._cuda_declaration(node))
            elif node.type == "operation":
                output.append(self._cuda_operation(node))
        
        return "\n".join(output)
    
    def _cuda_declaration(self, node: AETNode) -> str:
        """CUDA state declaration"""
        type_name = node.children[0].type
        name = node.value
        args = node.children[0].value
        
        if type_name == "State":
            dims = re.search(r'dimensions=(\d+)', args)
            dim = dims.group(1) if dims else "4096"
            return f"__device__ __managed__ float {name}{dim}];"
        
        return f"// {name} = {type_name}({args})"
    
    def _cuda_operation(self, node: AETNode) -> str:
        """CUDA operation"""
        result = node.value
        op = node.children[1].value
        left = node.children[0].value
        right = node.children[2].value
        
        if op == "@":
            return f"// {result} = cublasSgemm({left}, {right}) // GPU matrix multiply"
        
        return f"// {result} = {left} {op} {right}"


def transpile(source: str, target: str = "zig") -> str:
    """Convenience function for transpilation"""
    transpiler = AEONTranspiler(target)
    return transpiler.transpile(source, target)


